/**
 * Cross-platform MD5 implementation in pure TypeScript (RFC 1321 compliant).
 * Runs seamlessly in both Desktop (Electron) and Mobile (iOS / Android WebView)
 * without depending on Node.js "crypto" module.
 */

export const BAIDU_CHUNK_SIZE = 4 * 1024 * 1024; // 4MB

function toUint8Array(data: ArrayBuffer | Uint8Array | ArrayLike<number>): Uint8Array {
  if (data instanceof Uint8Array) {
    return data;
  }
  if (data instanceof ArrayBuffer) {
    return new Uint8Array(data);
  }
  if (ArrayBuffer.isView(data)) {
    return new Uint8Array(data.buffer, data.byteOffset, data.byteLength);
  }
  return new Uint8Array(data as any);
}

/**
 * Standard MD5 implementation working on pure Uint8Array / ArrayBuffer
 */
export function calculateMd5(input: ArrayBuffer | Uint8Array | ArrayLike<number>): string {
  const bytes = toUint8Array(input);
  const len = bytes.length;

  // Pre-processing: padding
  // Calculate padded length in 32-bit words
  // len * 8 bits + 1 bit + padding + 64-bit length = multiple of 512 bits (64 bytes)
  const nWords = (((len + 8) >> 6) + 1) * 16;
  const words = new Int32Array(nWords);

  for (let i = 0; i < len; i++) {
    words[i >> 2] |= bytes[i] << ((i % 4) * 8);
  }
  words[len >> 2] |= 0x80 << ((len % 4) * 8);
  // Append length in bits (64-bit integer, low 32 bits and high 32 bits)
  const bitLen = len * 8;
  words[nWords - 2] = bitLen & 0xffffffff;
  words[nWords - 1] = Math.floor(len / 0x20000000);

  // Initialize MD5 state variables
  let a = 1732584193;
  let b = -271733879;
  let c = -1732584194;
  let d = 271733878;

  function cmn(q: number, a: number, b: number, x: number, s: number, t: number): number {
    a = (a + q + x + t) | 0;
    return (((a << s) | (a >>> (32 - s))) + b) | 0;
  }

  function ff(a: number, b: number, c: number, d: number, x: number, s: number, t: number): number {
    return cmn((b & c) | (~b & d), a, b, x, s, t);
  }

  function gg(a: number, b: number, c: number, d: number, x: number, s: number, t: number): number {
    return cmn((b & d) | (c & ~d), a, b, x, s, t);
  }

  function hh(a: number, b: number, c: number, d: number, x: number, s: number, t: number): number {
    return cmn(b ^ c ^ d, a, b, x, s, t);
  }

  function ii(a: number, b: number, c: number, d: number, x: number, s: number, t: number): number {
    return cmn(c ^ (b | ~d), a, b, x, s, t);
  }

  for (let i = 0; i < nWords; i += 16) {
    const olda = a;
    const oldb = b;
    const oldc = c;
    const oldd = d;

    // Round 1
    a = ff(a, b, c, d, words[i + 0], 7, -680876936);
    d = ff(d, a, b, c, words[i + 1], 12, -389564586);
    c = ff(c, d, a, b, words[i + 2], 17, 606105819);
    b = ff(b, c, d, a, words[i + 3], 22, -1044525330);
    a = ff(a, b, c, d, words[i + 4], 7, -176418897);
    d = ff(d, a, b, c, words[i + 5], 12, 1200080426);
    c = ff(c, d, a, b, words[i + 6], 17, -1473231341);
    b = ff(b, c, d, a, words[i + 7], 22, -45705983);
    a = ff(a, b, c, d, words[i + 8], 7, 1770035416);
    d = ff(d, a, b, c, words[i + 9], 12, -1958414417);
    c = ff(c, d, a, b, words[i + 10], 17, -42063);
    b = ff(b, c, d, a, words[i + 11], 22, -1990404162);
    a = ff(a, b, c, d, words[i + 12], 7, 1804603682);
    d = ff(d, a, b, c, words[i + 13], 12, -40341101);
    c = ff(c, d, a, b, words[i + 14], 17, -1502002290);
    b = ff(b, c, d, a, words[i + 15], 22, 1236535329);

    // Round 2
    a = gg(a, b, c, d, words[i + 1], 5, -165796510);
    d = gg(d, a, b, c, words[i + 6], 9, -1069501632);
    c = gg(c, d, a, b, words[i + 11], 14, 643717713);
    b = gg(b, c, d, a, words[i + 0], 20, -373897302);
    a = gg(a, b, c, d, words[i + 5], 5, -701558691);
    d = gg(d, a, b, c, words[i + 10], 9, 38016083);
    c = gg(c, d, a, b, words[i + 15], 14, -660478335);
    b = gg(b, c, d, a, words[i + 4], 20, -405537848);
    a = gg(a, b, c, d, words[i + 9], 5, 568446438);
    d = gg(d, a, b, c, words[i + 14], 9, -1019803690);
    c = gg(c, d, a, b, words[i + 3], 14, -187363961);
    b = gg(b, c, d, a, words[i + 8], 20, 1163531501);
    a = gg(a, b, c, d, words[i + 13], 5, -1444681467);
    d = gg(d, a, b, c, words[i + 2], 9, -51403784);
    c = gg(c, d, a, b, words[i + 7], 14, 1735328473);
    b = gg(b, c, d, a, words[i + 12], 20, -1926607734);

    // Round 3
    a = hh(a, b, c, d, words[i + 5], 4, -378558);
    d = hh(d, a, b, c, words[i + 8], 11, -2022574463);
    c = hh(c, d, a, b, words[i + 11], 16, 1839030562);
    b = hh(b, c, d, a, words[i + 14], 23, -35309556);
    a = hh(a, b, c, d, words[i + 1], 4, -1530992060);
    d = hh(d, a, b, c, words[i + 4], 11, 1272893353);
    c = hh(c, d, a, b, words[i + 7], 16, -155497632);
    b = hh(b, c, d, a, words[i + 10], 23, -1094730640);
    a = hh(a, b, c, d, words[i + 13], 4, 681279174);
    d = hh(d, a, b, c, words[i + 0], 11, -358537222);
    c = hh(c, d, a, b, words[i + 3], 16, -722521979);
    b = hh(b, c, d, a, words[i + 6], 23, 76029189);
    a = hh(a, b, c, d, words[i + 9], 4, -640364487);
    d = hh(d, a, b, c, words[i + 12], 11, -421815835);
    c = hh(c, d, a, b, words[i + 15], 16, 530742520);
    b = hh(b, c, d, a, words[i + 2], 23, -995338651);

    // Round 4
    a = ii(a, b, c, d, words[i + 0], 6, -198630844);
    d = ii(d, a, b, c, words[i + 7], 10, 1126891415);
    c = ii(c, d, a, b, words[i + 14], 15, -1416354905);
    b = ii(b, c, d, a, words[i + 5], 21, -57434055);
    a = ii(a, b, c, d, words[i + 12], 6, 1700485571);
    d = ii(d, a, b, c, words[i + 3], 10, -1894986606);
    c = ii(c, d, a, b, words[i + 10], 15, -1051523);
    b = ii(b, c, d, a, words[i + 1], 21, -2054922799);
    a = ii(a, b, c, d, words[i + 8], 6, 1873313359);
    d = ii(d, a, b, c, words[i + 15], 10, -30611744);
    c = ii(c, d, a, b, words[i + 6], 15, -1560198380);
    b = ii(b, c, d, a, words[i + 13], 21, 1309151649);
    a = ii(a, b, c, d, words[i + 4], 6, -145523070);
    d = ii(d, a, b, c, words[i + 11], 10, -1120210379);
    c = ii(c, d, a, b, words[i + 2], 15, 718787259);
    b = ii(b, c, d, a, words[i + 9], 21, -343485551);

    a = (a + olda) | 0;
    b = (b + oldb) | 0;
    c = (c + oldc) | 0;
    d = (d + oldd) | 0;
  }

  function rhex(n: number): string {
    let s = "";
    for (let j = 0; j <= 3; j++) {
      s += "0123456789abcdef".charAt((n >> (j * 8 + 4)) & 0x0f) +
           "0123456789abcdef".charAt((n >> (j * 8)) & 0x0f);
    }
    return s;
  }

  return (rhex(a) + rhex(b) + rhex(c) + rhex(d)).toLowerCase();
}

/**
 * Split buffer into 4MB chunks and calculate block_list (array of MD5s) for Baidu Netdisk API.
 * Uses Uint8Array slice to avoid Node.js Buffer dependence on Mobile.
 */
export function calculateBlockList(
  buffer: ArrayBuffer | Uint8Array
): { blockList: string[]; chunks: Uint8Array[] } {
  const bytes = toUint8Array(buffer);
  const blockList: string[] = [];
  const chunks: Uint8Array[] = [];

  if (bytes.length === 0) {
    const emptyMd5 = calculateMd5(bytes);
    blockList.push(emptyMd5);
    chunks.push(bytes);
    return { blockList, chunks };
  }

  for (let offset = 0; offset < bytes.length; offset += BAIDU_CHUNK_SIZE) {
    const end = Math.min(offset + BAIDU_CHUNK_SIZE, bytes.length);
    const chunk = bytes.subarray(offset, end);
    chunks.push(chunk);
    blockList.push(calculateMd5(chunk));
  }

  return { blockList, chunks };
}
