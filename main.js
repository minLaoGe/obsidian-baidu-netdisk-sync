var Mutex = class {
  constructor() {
    this.current = Promise.resolve();
  }
  async acquire(task) {
    let release;
    const next = new Promise((resolve) => {
      release = resolve;
    });
    const previous = this.current;
    this.current = next;
    await previous;
    try {
      return await task();
    } finally {
      release();
    }
  }
  isLocked() {
    let locked = true;
    Promise.race([
      this.current.then(() => false),
      Promise.resolve(true)
    ]).then((val) => {
      locked = val;
    });
    return locked;
  }
};
var FifoQueue = class {
  constructor() {
    this.queue = [];
    this.isProcessing = false;
  }
  /**
   * Enqueue a task to be executed strictly in FIFO order.
   */
  enqueue(task) {
    return new Promise((resolve, reject) => {
      this.queue.push(async () => {
        try {
          const result = await task();
          resolve(result);
        } catch (err) {
          reject(err);
        }
      });
      this.processNext();
    });
  }
  async processNext() {
    if (this.isProcessing) return;
    if (this.queue.length === 0) return;
    this.isProcessing = true;
    const task = this.queue.shift();
    if (task) {
      try {
        await task();
      } catch (err) {
        console.error("Queue task execution error:", err);
      } finally {
        this.isProcessing = false;
        this.processNext();
      }
    } else {
      this.isProcessing = false;
    }
  }
  get length() {
    return this.queue.length;
  }
  clear() {
    this.queue = [];
  }
};
var DebounceManager = class {
  constructor() {
    this.timers = /* @__PURE__ */ new Map();
  }
  debounce(key, delayMs, fn) {
    if (this.timers.has(key)) {
      window.clearTimeout(this.timers.get(key));
    }
    const timer = window.setTimeout(() => {
      this.timers.delete(key);
      fn();
    }, delayMs);
    this.timers.set(key, timer);
  }
  cancel(key) {
    if (this.timers.has(key)) {
      window.clearTimeout(this.timers.get(key));
      this.timers.delete(key);
    }
  }
  clearAll() {
    for (const timer of this.timers.values()) {
      window.clearTimeout(timer);
    }
    this.timers.clear();
  }
};

